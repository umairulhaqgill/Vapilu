async def call_connector(connector: str, operation: str, values: dict) -> tuple[bool, dict]:
    """
    Runs one action node's connector call against the Connector Gateway.
    Returns (ok, result) - result is either the connector's real result or
    a small {"error": ...} dict. A Gateway that's unreachable or errors
    degrades to ok=False rather than raising, same "downstream failures
    degrade the call rather than end it" convention as the NLU/TTS calls -
    a booking failure should route the flow's on_error path, not crash
    the whole call the caller is still on.
    """
    try:
        response = await http_client.post(
            f"{CONNECTOR_GATEWAY_URL}/call",
            json={
                "connector": connector,
                "operation": operation,
                "values": values,
                "token": CONNECTOR_GATEWAY_TOKEN,
            },
        )
        response.raise_for_status()
        data = response.json()
        if data.get("ok"):
            return True, data.get("result") or {}
        return False, {"error": data.get("error", "connector reported failure")}
    except Exception as e:
        logger.exception("Connector Gateway call failed for %s.%s: %s", connector, operation, e)
        return False, {"error": "connector gateway unreachable"}


async def load_tenant(tenant_id: str | None) -> dict | None:
    """
    Fetches a tenant's config at call start. Returns None if no tenant was
    specified, the tenant doesn't exist, or the service is unreachable - in
    which case the Orchestrator falls back to generic defaults rather than
    refusing the call. A config lookup failure shouldn't mean a customer
    can't reach anyone.
    """
    if not tenant_id:
        return None
    try:
        response = await http_client.get(
            f"{TENANT_SERVICE_URL}/tenants/{tenant_id}",
            params={"token": TENANT_SERVICE_TOKEN},
        )
        if response.status_code == 404:
            logger.warning("Unknown tenant_id %r - using defaults", tenant_id)
            return None
        response.raise_for_status()
        return response.json()
    except Exception as e:
        logger.exception("Failed to load tenant %r: %s", tenant_id, e)
        return None


async def load_flows(tenant_id: str | None) -> list[dict]:
    """
    Fetches a tenant's active flows at call start. Failure returns an empty
    list rather than raising - the bot degrades to plain conversation
    instead of the call failing outright.
    """
    if not tenant_id:
        return []
    try:
        response = await http_client.get(
            f"{TENANT_SERVICE_URL}/tenants/{tenant_id}/flows",
            params={"token": TENANT_SERVICE_TOKEN},
        )
        response.raise_for_status()
        return response.json().get("flows", [])
    except Exception as e:
        logger.exception("Failed to load flows for %r: %s", tenant_id, e)
        return []

