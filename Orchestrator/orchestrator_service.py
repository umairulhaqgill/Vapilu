class PlaybackClock:
    """
    Tracks when the audio we've sent will actually finish playing.

    Why this exists: the enclosing response task must stay alive as long as
    the caller is still HEARING the reply, otherwise barge-in has nothing to
    cancel (see handle_call). But sleeping after each individual sentence -
    the obvious way to do that - blocks the next sentence's synthesis until
    the previous one finishes playing, which inserts an audible gap of
    silence between every sentence while TTS works.

    Instead we track a running deadline: each sentence's audio pushes the
    deadline out by its own duration, and we only actually sleep once at the
    end. Synthesis for sentence 2 therefore happens WHILE sentence 1 is
    still playing on the client (whose queue preserves ordering), so the
    audio comes out continuous.
    """

    def __init__(self, audio_format: dict):
        self._bytes_per_second = (
            audio_format["sample_rate"] * audio_format["sample_width"] * audio_format["channels"]
        )
        self._deadline: float | None = None

    def add_audio(self, num_bytes: int):
        if self._bytes_per_second <= 0 or num_bytes <= 0:
            return
        duration = num_bytes / self._bytes_per_second
        now = asyncio.get_event_loop().time()
        # If previous audio has already finished playing, this starts now;
        # otherwise it queues behind what's still playing.
        start_from = max(now, self._deadline) if self._deadline is not None else now
        self._deadline = start_from + duration

    async def wait_until_finished(self):
        if self._deadline is None:
            return
        remaining = self._deadline - asyncio.get_event_loop().time()
        if remaining > 0:
            await asyncio.sleep(remaining)


def _fallback_ack(run) -> str:
    """
    Spoken filler for a turn where nothing got said out loud - neither the
    LLM nor a flow `say` node (see the call site in respond_to, AFTER the
    flow has applied this turn's values and advanced). Names whatever the
    flow needs next rather than a dead-end "thanks", so the conversation
    keeps moving instead of making the caller prompt again just to hear
    the next question. Call this post-advance, not from inside
    speak_reply_text - beforehand, `run` still reflects the PREVIOUS turn
    and would ask about a field the caller may have just answered.

    Two shapes of "next", both real fields on FlowRun:
    - CONFIRMING: every required field for this node is already in, so
      extraction_fields() is empty - there's nothing left to COLLECT, but
      there IS a rendered confirm line waiting to be read back. Missing
      this case was the actual bug: a turn that happened to complete the
      LAST field landed here with nothing to say, same as true silence.
    - Otherwise: name the next still-missing field, same as before.
    """
    if run is not None:
        if run.status == RunStatus.CONFIRMING:
            confirm = run.rendered_confirm()
            if confirm:
                return confirm
        missing = run.extraction_fields()
        if missing:
            return f"Got it. And {missing[0]['prompt']}?"
    return "Got it, thanks."


async def speak_text(tts_ws, client_ws, text: str, clock: "PlaybackClock"):
    """
    Sends one complete sentence to the (already open, persistent) TTS
    Service connection and relays the resulting audio straight to the
    caller as it's generated. This is what actually lets the bot start
    speaking sentence 1 while the LLM is still generating sentence 2.

    Returns as soon as the audio has been relayed - it does NOT wait for
    playback. The caller records the duration on the shared PlaybackClock
    and waits once at the end instead, so synthesis of the next sentence
    overlaps with playback of this one.

    Failures here are logged and swallowed, not raised - losing the audio
    for one sentence shouldn't end the whole call.
    """
    if tts_ws is None:
        logger.error("No TTS connection available - skipping audio for this sentence.")
        return

    try:
        await tts_ws.send(text)
        bytes_sent = 0
        while True:
            message = await tts_ws.recv()
            if isinstance(message, bytes):
                await client_ws.send_bytes(message)
                bytes_sent += len(message)
            else:
                data = json.loads(message)
                if data.get("event") == "utterance_end":
                    break
                if "error" in data:
                    logger.error("TTS Service reported an error: %s", data.get("detail"))
                    break

        clock.add_audio(bytes_sent)
    except Exception as e:
        logger.exception("TTS Service call failed: %s", e)


async def stream_nlu_reply(
    conversation_history: list[dict],
    tenant: dict | None = None,
    flow_instructions: str | None = None,
    extract_fields: list[dict] | None = None,
):
    """
    Calls the NLU/LLM Service's streaming endpoint and yields text deltas as
    they arrive - this is what lets the Orchestrator react to the first few
    words instead of waiting for the whole reply to finish generating.

    The tenant's system_prompt_extra (and other context like business name
    and capabilities) is passed along so the LLM knows which business it's
    answering for. The NLU service stays stateless - it doesn't look
    tenants up itself, it just uses whatever context it's given.

    If the service is unreachable or errors before yielding anything, yields
    one safe fallback message instead - a call in progress shouldn't die
    just because one downstream service hiccuped.
    """
    payload = {"token": NLU_SERVICE_TOKEN, "conversation_history": conversation_history}
    if flow_instructions:
        payload["flow_instructions"] = flow_instructions
    if extract_fields:
        payload["extract_fields"] = extract_fields
    if tenant:
        payload["tenant_context"] = {
            "business_name": tenant.get("business_name"),
            "system_prompt_extra": tenant.get("system_prompt_extra", ""),
            "capabilities": tenant.get("capabilities", []),
            "business_hours": tenant.get("business_hours"),
            "escalation_phone": tenant.get("escalation_phone"),
        }

    yielded_anything = False
    try:
        async with http_client.stream(
            "POST",
            NLU_SERVICE_URL,
            json=payload,
        ) as response:
            response.raise_for_status()
            async for line in response.aiter_lines():
                if not line:
                    continue
                data = json.loads(line)
                if "delta" in data:
                    yielded_anything = True
                    yield data
                elif "extracted" in data:
                    # A tool-call-only turn (no accompanying reply text) is
                    # a real, valid response - not silence. Missing this
                    # made the fallback message fire on a successful
                    # extraction whenever the model chose not to also
                    # narrate in words, which qwen3.5 does far more often
                    # than the Claude models this was written against.
                    yielded_anything = True
                    yield data
                elif "error" in data:
                    logger.error("NLU Service reported an error mid-stream: %s", data["error"])
                    break
    except Exception as e:
        logger.exception("NLU Service call failed: %s", e)

    if not yielded_anything:
        yield {"delta": "Sorry, I'm having trouble understanding right now. Could you say that again?"}


