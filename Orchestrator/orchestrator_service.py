"""
Orchestrator — the conversation state machine.

  Caller  <---WebSocket--->  Orchestrator  <---WebSocket--->  STT Service
                                    |
                                    +---WebSocket---> NLU/LLM Service (HTTP)
                                    +---WebSocket---> TTS Service

- Caller connects to  ws://<host>:8001/ws/call?token=...
- Caller sends raw audio bytes (same format the STT Service expects)
- Orchestrator forwards that audio to the STT Service (as a client of it —
  same role your test_mic_stream.py script has been playing)
- On each transcript event, the Orchestrator advances its call state machine,
  calls the NLU/LLM Service for a real reply, and streams that reply through
  the sentence chunker into the TTS Service - so the caller hears the first
  sentence while later ones are still being generated by the LLM.
- Barge-in: response generation (NLU + TTS) runs as a separate cancellable
  task from STT event reading, specifically so that if the caller starts
  talking while the bot is responding, the Orchestrator notices immediately
  (rather than being stuck awaiting the response) and can cancel it, stop
  the caller's audio playback, and reconnect to TTS to guarantee no stale
  audio from the interrupted reply leaks into the next one.

Run with:
    uvicorn orchestrator_service:app --reload --port 8001

Needs the STT, NLU, and TTS Services already running (ports 8000/8002/8003).
"""

